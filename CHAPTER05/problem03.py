# 2번에서는 4개의 함수를 작성하였다. 하나의 함수 calc() 안에서
# 덧셈, 뺄셈, 곱셈, 나눗셈을 모두 수행하고 4개의 계산값을 동시에 반환하도록 수정하라.

# 실행 결과
"""
첫 번째 정수를 입력하십시오: 10
두 번째 정수를 입력하십시오: 20

30, -10, 200, 0.5가 반환되었습니다.
"""

def calc(a, b):
    return a + b, a - b, a * b, a / b

a = int(input("첫 번째 정수를 입력하십시오: "))
b = int(input("두 번째 정수를 입력하십시오: "))

add, sub, mul, div = calc(a, b)

print(f"{add}, {sub}, {mul}, {div}가 반환되었습니다.")