# 사용자로부터 두개의 정수를 받아서 정수의 합, 정수의차, 정수의 곱, 정수의 평균 ,큰 수, 작은 수를 계산하여 화면에
# 츌력하는 프로그램을 작성하라. 파이썬이 제공하는 내장함수 max(x, y), min(x, y)을 사용해보자.

# 실행 결과
"""
x: 10
y: 20
두수의 합: 30
두수의 차: -10
두수의 곱: 200
두수의 평균: 15.0
큰 수: 20
작은 수: 10
"""

x = int(input("x: "))
y = int(input("y: "))

print("두수의 합:", x + y)
print("두수의 차:", x - y)
print("두수의 곱:", x * y)
print("두수의 평균:", (x + y) / 2)
print("큰 수:", max(x, y))
print("작은 수:", min(x, y))